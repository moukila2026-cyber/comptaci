export function traducteur(langue) {
  const table = dict[langue] || dict.fr;
  return function t(cle, variables) {
    let texte = table[cle] || dict.fr[cle] || cle;
    if (variables) {
      for (const [k, v] of Object.entries(variables)) {
        texte = texte.replace(`{${k}}`, v);
      }
    }
    return texte;
  };
}

export function getLangueInitiale() {
  try {
    const sauvegardee = localStorage.getItem("comptaci:langue");
    if (sauvegardee && dict[sauvegardee]) return sauvegardee;
  } catch (e) {}
  return "fr";
}

export function sauvegarderLangue(langue) {
  try {
    localStorage.setItem("comptaci:langue", langue);
  } catch (e) {}
}
